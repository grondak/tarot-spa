const RANKS = ["Ace","Two","Three","Four","Five","Six","Seven","Eight","Nine","Ten","Page","Knight","Queen","King"];

function minorSuit(suit, descriptions) {
  return descriptions.map((desc, i) => ({
    name: `${RANKS[i]} of ${suit}`,
    cardType: suit,
    number: i + 1,
    ...desc,
  }));
}

